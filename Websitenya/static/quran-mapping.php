/**
 * Get the last Surah and Ayah for a specific juz and page
 * 
 * @param int $juz Juz number (1-30)
 * @param string $page Page number (e.g., '1A', '1B', '2A', ..., '10B')
 * @return array|null Array with surah and ayah info, or null if not found
 */
function getSurahAyahFromPage($juz, $page) {
    $mapping = getQuranMapping();
    
    if (!isset($mapping[$juz])) {
        return null;
    }
    
    // Convert page format (1A -> 1, 1B -> 2, 2A -> 3, 2B -> 4, etc.)
    $pageNum = intval($page);
    $pageSuffix = str_replace($pageNum, '', $page);
    $pageIndex = ($pageNum - 1) * 2 + ($pageSuffix === 'A' ? 1 : 2);
    
    if (isset($mapping[$juz][$pageIndex])) {
        return $mapping[$juz][$pageIndex];
    }
    
    return null;
}

/**
 * Get the last achievement as Surah and Ayah format
 * 
 * @param string $type Achievement type (ziyadah, setengah_juz, juziyah, syahadah)
 * @param int|null $juz Juz number
 * @param string|null $halaman Page number (for ziyadah)
 * @return string Formatted string like "Juz 29, QS. Al-Insan, Ayat 5"
 */
function formatLastAchievement($type, $juz, $halaman) {
    if ($type === 'ziyadah' && $halaman) {
        $surahAyah = getSurahAyahFromPage($juz, $halaman);
        if ($surahAyah && $surahAyah['surah']) {
            return "Juz {$juz}, QS. {$surahAyah['surah']}, Ayat {$surahAyah['ayah']}";
        }
        return "Juz {$juz}, Halaman {$halaman}";
    } elseif (in_array($type, ['setengah_juz', 'juziyah']) && $juz) {
        // For setengah_juz and juziyah, get the last page of that juz
        $surahAyah = getSurahAyahFromPage($juz, '10B');
        if ($surahAyah && $surahAyah['surah']) {
            return "Juz {$juz}, QS. {$surahAyah['surah']}, Ayat {$surahAyah['ayah']}";
        }
        return "Juz {$juz}";
    } elseif ($type === 'syahadah') {
        // For syahadah, it covers multiple juz
        return "Syahadah {$juz}";
    }
    
    return "Juz {$juz}";
}
